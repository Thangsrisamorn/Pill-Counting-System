from ultralytics import YOLO

# 1. โหลดโมเดล YOLOv8 โครงสร้างขนาด Small (s)
model = YOLO('yolov8s.pt')

if __name__ == '__main__':
    # 2. เริ่มการเทรน (Training)
    results = model.train(
        data='data.yaml',           # ไฟล์ตั้งค่า Dataset
        epochs=50,                  # จำนวนรอบการเรียนรู้
        imgsz=640,                  # ขนาดรูปภาพมาตรฐาน
        batch=8,                    # 👈 ลด Batch ลงมาที่ 8 ตามที่คุณตั้งไว้ (เยี่ยมมากครับ)
        workers=2,                  # 👈 เพิ่มบรรทัดนี้! เพื่อแก้ปัญหา WinError 1455 (RAM เต็ม)
        project='Pill_Project',     # ชื่อโฟลเดอร์หลักสำหรับเก็บผลลัพธ์
        name='yolov8s_webcam',      # ชื่อโฟลเดอร์ย่อยในการรันครั้งนี้
        
        # ==========================================
        # ⚙️ Data Augmentation (เน้นรูปทรง ลดการจำสี)
        # ==========================================
        hsv_h=0.5,      # สุ่มเปลี่ยนเฉดสี (Hue) อย่างหนัก
        hsv_s=0.9,      # สุ่มเปลี่ยนความสดของสี (Saturation) ทำให้มีทั้งภาพสีสดและสีซีด
        hsv_v=0.9,      # สุ่มเปลี่ยนความสว่าง (Value) ป้องกันปัญหาแสงจาก Webcam
        degrees=180.0,  # สุ่มหมุนภาพสูงสุด 180 องศา (สำคัญมากสำหรับเม็ดยาที่ตกแบบสุ่มมุม)
        fliplr=0.5,     # สุ่มพลิกซ้ายขวา 50%
        flipud=0.5      # สุ่มพลิกบนล่าง 50%
    )
    
    print("🎉 เทรนโมเดลเสร็จสมบูรณ์!")